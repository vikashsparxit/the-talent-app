import { defineConfig } from "vite";
import react from "@vitejs/plugin-react-swc";
import path from "path";
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { VitePWA } from "vite-plugin-pwa";
import { maskableIconFile, maskableIconsPlugin } from "./scripts/maskable-icons";

// Push handlers live in public/push-sw.js. Importing them with a content hash
// changes the generated sw.js whenever they change, so browsers always pick up
// the new handlers.
const pushSwVersion = createHash("sha256")
  .update(readFileSync(path.resolve(__dirname, "public/push-sw.js")))
  .digest("hex")
  .slice(0, 12);

// https://vitejs.dev/config/
export default defineConfig(({ mode }) => ({
  server: {
    host: "::",
    port: 8080,
    hmr: {
      overlay: false,
    },
  },
  plugins: [
    react(),
    maskableIconsPlugin(path.resolve(__dirname, "public/android-chrome-512x512.png")),
    VitePWA({
      registerType: "autoUpdate",
      // Registered from src/lib/pwa.ts with virtual:pwa-register, which reloads
      // the page once when an updated worker activates. The injected
      // registerSW.js only registered the worker and never reloaded, so open
      // tabs and installed apps kept running a build whose files were gone.
      injectRegister: false,
      includeAssets: ["favicon.ico", "apple-touch-icon.png", "android-chrome-192x192.png", "android-chrome-512x512.png", "the-talent-app-icon.png"],
      // The only web manifest: index.html gets its <link> at build time.
      manifest: {
        id: "/",
        name: "The Talent App",
        short_name: "Talent App",
        description: "Recruitment pipeline and talent management",
        theme_color: "#D64541",
        background_color: "#ffffff",
        display: "standalone",
        orientation: "portrait-primary",
        start_url: "/",
        scope: "/",
        icons: [
          { src: "/android-chrome-192x192.png", sizes: "192x192", type: "image/png", purpose: "any" },
          { src: "/android-chrome-512x512.png", sizes: "512x512", type: "image/png", purpose: "any" },
          // Generated by scripts/maskable-icons.ts, artwork inside the safe zone.
          { src: `/${maskableIconFile(192)}`, sizes: "192x192", type: "image/png", purpose: "maskable" },
          { src: `/${maskableIconFile(512)}`, sizes: "512x512", type: "image/png", purpose: "maskable" },
        ],
      },
      workbox: {
        globPatterns: ["**/*.{js,css,html,ico,png,svg,woff2,webmanifest}"],
        maximumFileSizeToCacheInBytes: 5 * 1024 * 1024,
        navigateFallback: "/index.html",
        navigateFallbackDenylist: [/^\/api/, /^\/assets\//],
        // The new worker takes over open pages straight away (registerSW then
        // reloads them) and drops the previous build's precache.
        skipWaiting: true,
        clientsClaim: true,
        cleanupOutdatedCaches: true,
        importScripts: [`/push-sw.js?v=${pushSwVersion}`],
        // Hashed /assets/*.js must not use StaleWhileRevalidate — it kept serving
        // pre-fix bundles (old pipeline tab-count queries) after deploy.
      },
    }),
  ],
  resolve: {
    alias: {
      "@": path.resolve(__dirname, "./src"),
    },
  },
}));
